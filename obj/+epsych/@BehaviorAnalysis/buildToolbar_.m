function buildToolbar_(self)
% buildToolbar_(self)
% One tool per thing done often, glyphs from gui.toolbarIcon: open a root,
% rescan, save; settings, generate script, export tables, export figure;
% the overlay of the checked staircases, review the shown session, the
% subject's learning curves; and hide the shown session.
%
% See also: epsych.BehaviorAnalysis.buildMenus_, gui.toolbarIcon

tb = uitoolbar(self.H.figure);
self.H.toolbar = tb;

self.H.tb_browse = uipushtool(tb, 'Icon', gui.toolbarIcon("browse"), ...
    'Tooltip', 'Open a data root (Ctrl+O)', 'ClickedCallback', @(~,~) self.openRoot(""));
self.H.tb_refresh = uipushtool(tb, 'Icon', gui.toolbarIcon("refresh"), ...
    'Tooltip', 'Rescan the root for new or changed files (F5)', 'ClickedCallback', @(~,~) self.rescan());
self.H.tb_save = uipushtool(tb, 'Icon', gui.toolbarIcon("save"), ...
    'Tooltip', 'Save the project file (Ctrl+S)', 'ClickedCallback', @(~,~) self.saveProject());

self.H.tb_settings = uipushtool(tb, 'Icon', gui.toolbarIcon("gear"), 'Separator', 'on', ...
    'Tooltip', 'Analysis settings and presets', 'ClickedCallback', @(~,~) self.settingsDialog_());
self.H.tb_script = uipushtool(tb, 'Icon', gui.toolbarIcon("script"), ...
    'Tooltip', 'Generate a MATLAB script that reproduces the checked sessions'' analysis (Ctrl+G)', ...
    'ClickedCallback', @(~,~) self.scriptMenu_("selected"));
self.H.tb_export = uipushtool(tb, 'Icon', gui.toolbarIcon("export"), ...
    'Tooltip', 'Export the checked sessions'' tables (Ctrl+E)', 'ClickedCallback', @(~,~) self.exportDialog_());
self.H.tb_figure = uipushtool(tb, 'Icon', gui.toolbarIcon("figure"), ...
    'Tooltip', 'Export the figure on this tab (Ctrl+Shift+F)', 'ClickedCallback', @(~,~) self.figureMenu_());

self.H.tb_overlay = uipushtool(tb, 'Icon', gui.toolbarIcon("overlay"), 'Separator', 'on', ...
    'Tooltip', 'Overlay the checked sessions'' staircases (Compare tab)', ...
    'ClickedCallback', @(~,~) localOverlay(self));
self.H.tb_review = uipushtool(tb, 'Icon', gui.toolbarIcon("review"), ...
    'Tooltip', 'Review the shown session in its behavior GUI (Ctrl+R)', ...
    'ClickedCallback', @(~,~) self.sessionAction_("review"));
self.H.tb_subjects = uipushtool(tb, 'Icon', gui.toolbarIcon("subjects"), ...
    'Tooltip', 'The selected subject''s learning curves (Subject tab, Ctrl+2)', ...
    'ClickedCallback', @(~,~) self.userShowTab_("Subject"));
self.H.tb_hide = uipushtool(tb, 'Icon', gui.toolbarIcon("hide"), ...
    'Tooltip', 'Hide or unhide the shown session (Del)', ...
    'ClickedCallback', @(~,~) self.sessionAction_("hide"));

end


function localOverlay(self)
if self.setFacet("Kind", "overlay")
    self.showTab("Compare");
end
end
