function struct_out = toStruct(obj)
    % struct_out = toStruct(obj)
    % Convert the protocol to a serializable struct for JSON or MAT persistence.
    %
    % Returns:
    %	struct_out	- Serializable struct containing metadata, options, compiled state,
    %			  and interface definitions.

    struct_out = struct();
    struct_out.formatVersion    = obj.meta.formatVersion;
    struct_out.epsychVersion    = obj.meta.epsychVersion;
    struct_out.createdDate      = char(obj.meta.createdDate);
    struct_out.lastModified     = char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));
    struct_out.protocolVersion  = obj.meta.protocolVersion;

    struct_out.Options = obj.Options;
    struct_out.Info = obj.Info;

    % Serialize COMPILED without hw.Parameter handles (cannot be JSON encoded;
    % parameters are regenerated by compile() after loading).
    compiledOut = obj.COMPILED;
    if isstruct(compiledOut) && isfield(compiledOut, 'parameters')
        compiledOut = rmfield(compiledOut, 'parameters');
    end
    struct_out.COMPILED = compiledOut;

    struct_out.InterfaceData = {};
    for ifaceIdx = 1:length(obj.Interfaces)
        iface = obj.Interfaces(ifaceIdx);
        ifaceStruct = struct();
        ifaceStruct.Type = char(iface.Type);
        ifaceStruct.ClassName = class(iface);

        if isprop(iface, 'Server') && ~isempty(iface.Server)
            ifaceStruct.Server = char(iface.Server);
        end
        if isprop(iface, 'ConnectionType') && ~isempty(iface.ConnectionType)
            ifaceStruct.ConnectionType = char(iface.ConnectionType);
        end
        if isprop(iface, 'Host') && ~isempty(iface.Host)
            ifaceStruct.Host = char(iface.Host);
        end
        if isprop(iface, 'Port') && ~isempty(iface.Port)
            % 'Port' is a TCP port number on hw.Intan_RHX but a serial port
            % name on hw.Teensy. Coercing everything to double would turn
            % 'COM6' into its character codes, so preserve the backend's type.
            if ischar(iface.Port) || isstring(iface.Port)
                ifaceStruct.Port = char(iface.Port);
            else
                ifaceStruct.Port = double(iface.Port);
            end
        end
        if isprop(iface, 'SettingsFile') && ~isempty(iface.SettingsFile)
            ifaceStruct.SettingsFile = char(iface.SettingsFile);
        end
        if isprop(iface, 'SamplingRate') && ~isempty(iface.SamplingRate) && iface.SamplingRate > 0
            ifaceStruct.SamplingRate = double(iface.SamplingRate);
        end
        if isprop(iface, 'ControllerType') && ~isempty(iface.ControllerType)
            ifaceStruct.ControllerType = char(iface.ControllerType);
        end
        if isprop(iface, 'BaudRate') && ~isempty(iface.BaudRate)
            ifaceStruct.BaudRate = double(iface.BaudRate);
        end
        if isprop(iface, 'AutoDetect') && ~isempty(iface.AutoDetect)
            ifaceStruct.AutoDetect = logical(iface.AutoDetect);
        end
        if isprop(iface, 'DeviceSerial') && ~isempty(iface.DeviceSerial)
            ifaceStruct.DeviceSerial = char(iface.DeviceSerial);
        end

        rawModules = iface.Module;
        if isempty(rawModules)
            moduleList = {};
        elseif isa(rawModules, 'hw.Module')
            moduleList = num2cell(reshape(rawModules, 1, []));
        else
            moduleList = {};
        end

        ifaceStruct.Modules = {};
        for moduleIdx = 1:length(moduleList)
            module = moduleList{moduleIdx};
            moduleStruct = struct();
            moduleStruct.Label = module.Label;
            moduleStruct.Name = module.Name;
            moduleStruct.Index = double(module.Index);
            moduleStruct.Fs = module.Fs;
            moduleStruct.Info = module.Info;
            moduleStruct.Parameters = {};
            for paramIdx = 1:length(module.Parameters)
                moduleStruct.Parameters{end + 1} = module.Parameters(paramIdx).toStruct();
            end
            ifaceStruct.Modules{end + 1} = moduleStruct;
        end

        struct_out.InterfaceData{end + 1} = ifaceStruct;
    end
end
