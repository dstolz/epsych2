function buildCheckCalculationsTab(obj, parent)
% buildCheckCalculationsTab(obj, parent)
% Build the Check Calculations panel: exhaustive evaluation of calculated
% parameter Expressions over user-specified input values, using the exact
% runtime evaluator. One input field per variable involved in any
% calculation; fields accept scalar or vector MATLAB expressions and every
% combination is simulated.
%
% Parameters:
%	parent	- Parent container for the tab contents. Uses obj.Figure when omitted.
    if nargin < 2 || isempty(parent)
        parent = obj.Figure;
    end

    checkPanel = uipanel(parent, ...
        'Position', [20 20 1060 680], ...
        'Title', 'Check Calculations', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.976 0.981 0.989], ...
        'ForegroundColor', [0.24 0.32 0.42]);

    obj.CheckCalcRunButton = uibutton(checkPanel, 'push', ...
        'Text', 'Run Check', ...
        'Position', [20 618 110 30], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Recompile, then exhaustively evaluate every calculation over all combinations of the input values below.', ...
        'ButtonPushedFcn', @(~, ~) obj.refreshCheckCalculations());

    obj.CheckCalcComboLabel = uilabel(checkPanel, ...
        'Text', '', ...
        'Position', [142 620 280 26], ...
        'FontColor', [0.36 0.43 0.52], ...
        'FontAngle', 'italic');

    obj.CheckCalcStatusLabel = uilabel(checkPanel, ...
        'Text', 'Not checked', ...
        'Position', [430 620 610 26], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.22 0.28 0.36]);

    uilabel(checkPanel, ...
        'Text', 'Issues', ...
        'Position', [20 592 200 22], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.24 0.32 0.42]);

    obj.CheckCalcIssuesTable = uitable(checkPanel, ...
        'Position', [20 474 1020 118], ...
        'ColumnName', {'Severity', 'Where', 'Message'}, ...
        'ColumnWidth', {70, 250, 680}, ...
        'ColumnEditable', false, ...
        'ColumnSortable', true);

    uilabel(checkPanel, ...
        'Text', 'Inputs (scalar or vector MATLAB expressions)', ...
        'Position', [20 444 360 22], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.24 0.32 0.42]);

    obj.CheckCalcInputsPanel = uipanel(checkPanel, ...
        'Position', [20 200 380 244], ...
        'BackgroundColor', [0.976 0.981 0.989], ...
        'BorderType', 'line', ...
        'Scrollable', 'on');

    obj.CheckCalcAnalysisArea = uitextarea(checkPanel, ...
        'Position', [20 20 380 170], ...
        'Editable', 'off', ...
        'FontName', 'Courier New', ...
        'FontSize', 11, ...
        'Value', {''});

    uilabel(checkPanel, ...
        'Text', 'Exhaustive Results (runtime evaluator semantics)', ...
        'Position', [410 444 420 22], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.24 0.32 0.42]);

    obj.CheckCalcTrialsTable = uitable(checkPanel, ...
        'Position', [410 20 630 424], ...
        'ColumnEditable', false, ...
        'ColumnSortable', true);
end
