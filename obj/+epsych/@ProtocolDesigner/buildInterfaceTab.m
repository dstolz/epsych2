function buildInterfaceTab(obj, parent)
% buildInterfaceTab(obj, parent)
% Build the interface builder and interface/module registry controls.
%
% Parameters:
%	parent	- Parent container for the contents. Uses obj.Figure when omitted.
%
% Panel children are positioned against the panel's inner height (Position(4)
% minus the title band), so every top row keeps ~16 px of clearance below the
% panel title.
%
% These controls live in the dialog opened by onOpenInterfaceDialog rather than
% in the main window. Everything that reads them therefore has to tolerate their
% absence -- see refreshInterfaceSummary, refreshInterfaceBuilder, and
% getSelectedInterfaceSpec.
    if nargin < 2 || isempty(parent)
        parent = obj.Figure;
    end

    builderPanel = uipanel(parent, ...
        'Position', [12 505 396 183], ...
        'Title', 'Add Interface', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.972 0.978 0.986], ...
        'ForegroundColor', [0.22 0.30 0.40]);

    uilabel(builderPanel, ...
        'Text', 'Interface Type', ...
        'Position', [16 129 100 18], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.22 0.28 0.36]);

    obj.DropDownInterfaceType = uidropdown(builderPanel, ...
        'Position', [16 99 364 26], ...
        'BackgroundColor', [0.997 0.998 0.999], ...
        'Tooltip', 'Select the type of interface to add to this protocol.', ...
        'ValueChangedFcn', @(~, ~) obj.onInterfaceSpecChanged());

    obj.BtnAddInterface = uibutton(builderPanel, 'push', ...
        'Text', 'Add Interface', ...
        'Position', [262 63 118 28], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Add the selected interface type to the protocol (Ctrl+Shift+A).', ...
        'ButtonPushedFcn', @(~, ~) obj.onAddInterface());

    % Three wrapped lines: interface descriptions run past two lines at this width.
    obj.LabelInterfaceDescription = uilabel(builderPanel, ...
        'Text', '', ...
        'Position', [16 8 364 48], ...
        'FontAngle', 'italic', ...
        'FontColor', [0.36 0.43 0.52], ...
        'VerticalAlignment', 'top', ...
        'WordWrap', 'on');

    registryPanel = uipanel(parent, ...
        'Position', [12 12 396 481], ...
        'Title', 'Current Interfaces', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.976 0.981 0.989], ...
        'ForegroundColor', [0.22 0.30 0.40]);

    uilabel(registryPanel, ...
        'Text', 'Select an interface or module to focus filtering and parameter targets in the main window. Editable interfaces can also add or remove modules here.', ...
        'Position', [14 393 368 52], ...
        'FontAngle', 'italic', ...
        'WordWrap', 'on', ...
        'VerticalAlignment', 'top', ...
        'FontColor', [0.36 0.43 0.52]);

    obj.InterfaceTree = uitree(registryPanel, ...
        'Position', [14 94 368 291], ...
        'BackgroundColor', [1 1 1], ...
        'SelectionChangedFcn', @(~, evt) obj.onInterfaceRegistrySelected(evt));

    obj.BtnRemoveInterface = uibutton(registryPanel, 'push', ...
        'Text', 'Remove Selected Interface', ...
        'Position', [14 54 368 30], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Remove the selected interface and all its modules from the protocol.', ...
        'ButtonPushedFcn', @(~, ~) obj.onRemoveInterface());

    obj.BtnModifyInterface = uibutton(registryPanel, 'push', ...
        'Text', 'Options', ...
        'Position', [14 14 118 30], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Open options for the selected interface or module.', ...
        'ButtonPushedFcn', @(~, ~) obj.onModifyInterfaceOptions());

    obj.BtnAddModule = uibutton(registryPanel, 'push', ...
        'Text', 'Add Module', ...
        'Position', [140 14 118 30], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Add a new module to the selected interface (Ctrl+Shift+M).', ...
        'ButtonPushedFcn', @(~, ~) obj.onAddModule());

    obj.BtnRemoveModule = uibutton(registryPanel, 'push', ...
        'Text', 'Remove Module', ...
        'Position', [266 14 116 30], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Remove the selected module from its interface.', ...
        'ButtonPushedFcn', @(~, ~) obj.onRemoveModule());
end
