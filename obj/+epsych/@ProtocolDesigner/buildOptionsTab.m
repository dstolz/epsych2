function buildOptionsTab(obj, parent)
% buildOptionsTab(obj, parent)
% Build the protocol options controls for trial function and compile settings.
%
% Parameters:
%	parent	- Parent container for the tab contents. Uses obj.Figure when omitted.
    if nargin < 2 || isempty(parent)
        parent = obj.Figure;
    end

    % Panel content is laid out against the panel's inner height (Position(4)
    % minus the title band), so the top row must clear the title text.
    optionsPanel = uipanel(parent, ...
        'Position', [20 20 760 230], ...
        'Title', 'Protocol Options', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.976 0.981 0.989], ...
        'ForegroundColor', [0.24 0.32 0.42]);

    uilabel(optionsPanel, ...
        'Text', 'Core timing and runtime settings for compiled protocols.', ...
        'Position', [24 183 500 18], ...
        'FontAngle', 'italic', ...
        'FontColor', [0.38 0.45 0.55]);

    heroPanel = uipanel(parent, ...
        'Parent', optionsPanel, ...
        'Position', [18 51 724 118], ...
        'Title', 'Execution Settings', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.985 0.989 0.995], ...
        'ForegroundColor', [0.24 0.32 0.42]);

    uilabel(heroPanel, 'Text', 'Trial Function:', 'Position', [18 42 92 22], ...
        'FontWeight', 'bold');
    obj.EditTrialFunc = uieditfield(parent, 'text', ...
        'Parent', heroPanel, ...
        'Position', [118 40 400 26], ...
        'BackgroundColor', [0.997 0.998 0.999], ...
        'Tooltip', 'Name of the trial function called by the runtime to select the next trial (e.g. myTrialFcn).', ...
        'ValueChangedFcn', @(~, ~) obj.onOptionControlChanged());

    obj.CheckCompileAtRuntime = uicheckbox(parent, ...
        'Parent', heroPanel, ...
        'Text', 'Compile At Runtime', ...
        'Position', [550 58 160 22], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Recompile the trial matrix each time the protocol is loaded at runtime rather than using a pre-compiled version.', ...
        'ValueChangedFcn', @(~, ~) obj.onOptionControlChanged());

    obj.CheckIncludeWAVBuffers = uicheckbox(parent, ...
        'Parent', heroPanel, ...
        'Text', 'Include WAV Buffers', ...
        'Position', [550 26 160 22], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Include pre-loaded WAV audio buffers in the compiled protocol for playback during the experiment.', ...
        'ValueChangedFcn', @(~, ~) obj.onOptionControlChanged());

    uilabel(optionsPanel, ...
        'Text', 'Use the Preview tab to compile and inspect the resulting trial matrix.', ...
        'Position', [24 21 500 18], ...
        'FontColor', [0.35 0.42 0.52]);
end

