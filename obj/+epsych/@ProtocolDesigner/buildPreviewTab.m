function buildPreviewTab(obj, parent)
% buildPreviewTab(obj, parent)
% Build the compiled trial preview controls and summary table.
%
% Parameters:
%	parent	- Parent container for the tab contents. Uses obj.Figure when omitted.
    if nargin < 2 || isempty(parent)
        parent = obj.Figure;
    end

    previewPanel = uipanel(parent, ...
        'Position', [20 20 1060 660], ...
        'Title', 'Compiled Trial Preview', ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.976 0.981 0.989], ...
        'ForegroundColor', [0.24 0.32 0.42]);

    obj.BtnCompile = uibutton(parent, 'push', ...
        'Parent', previewPanel, ...
        'Text', 'Compile Protocol', ...
        'Position', [20 604 148 34], ...
        'FontWeight', 'bold', ...
        'Tooltip', 'Compile the protocol into a full trial matrix and display the results below.', ...
        'ButtonPushedFcn', @(~, ~) obj.onCompile());

    obj.LabelCompileSummary = uilabel(parent, ...
        'Parent', previewPanel, ...
        'Text', 'Not compiled', ...
        'Position', [188 604 368 32], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.22 0.28 0.36]);

    uibutton(parent, 'push', ...
        'Parent', previewPanel, ...
        'Text', 'Export: Workspace', ...
        'Position', [564 604 116 34], ...
        'Tooltip', 'Export the full compiled trial table to the base workspace.', ...
        'ButtonPushedFcn', @(~, ~) obj.onExportCompiledPreview('workspace'));

    uibutton(parent, 'push', ...
        'Parent', previewPanel, ...
        'Text', 'Export: MAT', ...
        'Position', [688 604 104 34], ...
        'Tooltip', 'Export the full compiled trial table to a MAT file.', ...
        'ButtonPushedFcn', @(~, ~) obj.onExportCompiledPreview('mat'));

    uibutton(parent, 'push', ...
        'Parent', previewPanel, ...
        'Text', 'Export: CSV', ...
        'Position', [800 604 104 34], ...
        'Tooltip', 'Export the full compiled trial table to a CSV file.', ...
        'ButtonPushedFcn', @(~, ~) obj.onExportCompiledPreview('csv'));

    uibutton(parent, 'push', ...
        'Parent', previewPanel, ...
        'Text', 'Export: XLSX', ...
        'Position', [912 604 128 34], ...
        'Tooltip', 'Export the full compiled trial table to an XLSX file.', ...
        'ButtonPushedFcn', @(~, ~) obj.onExportCompiledPreview('xlsx'));

    obj.TableCompiled = uitable(parent, ...
        'Parent', previewPanel, ...
        'Position', [20 20 1020 568], ...
        'ColumnSortable', true, ...
        'ColumnRearrangeable', true, ...
        'ColumnEditable', false);
end

