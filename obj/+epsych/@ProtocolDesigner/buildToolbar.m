function buildToolbar(obj)
% buildToolbar(obj)
% Build the command strip above the main panel.
% Call once from buildUI() before the parameter panel is created.
%
% The strip fronts the actions reached most often from the menus, plus the
% Interfaces and Protocol Options dialogs. Buttons are laid out left to right
% from a running cursor rather than from hardcoded x positions, so retitling or
% reordering an entry does not shift the rest by hand. Labels are text, not
% icons: an icon strip would need a legend for terms like "Check Calcs" that
% have no conventional glyph.
    obj.ToolbarPanel = uipanel(obj.Figure, ...
        'Position', [20 856 1340 46], ...
        'BackgroundColor', [0.930 0.940 0.955], ...
        'BorderType', 'line', ...
        'HighlightColor', [0.80 0.84 0.89]);

    cursorX = 10;

    obj.BtnNew = addButton_('New', 74, ...
        'Start a new empty protocol, discarding unsaved changes after confirmation.', ...
        @() obj.onNew());
    obj.BtnLoad = addButton_('Open...', 86, ...
        'Load a protocol from disk (Ctrl+O).', ...
        @() obj.onLoad());
    obj.BtnSave = addButton_('Save', 76, ...
        'Save the protocol to its current file (Ctrl+S). Prompts for a file name when the protocol has never been saved.', ...
        @() obj.onSave());

    addSeparator_();

    obj.BtnOpenInterfaceDialog = addButton_('Interfaces...', 112, ...
        'Open the Interfaces dialog to add, remove, and configure interfaces and their modules (Ctrl+Shift+I).', ...
        @() obj.onOpenInterfaceDialog());
    obj.BtnOpenOptionsDialog = addButton_('Options...', 100, ...
        'Open the Protocol Options dialog to configure trial function, compile settings, and WAV buffers (Ctrl+Shift+O).', ...
        @() obj.onOpenOptionsDialog());

    addSeparator_();

    obj.BtnToolbarCompile = addButton_('Compile', 92, ...
        'Compile the protocol into a full trial matrix (Ctrl+Shift+C).', ...
        @() obj.onCompile());
    obj.BtnOpenPreviewDialog = addButton_('Preview...', 100, ...
        'Compile the protocol and open a preview of the resulting trial matrix (Ctrl+Shift+V).', ...
        @() obj.onOpenCompiledPreviewDialog());
    obj.BtnOpenCheckCalcDialog = addButton_('Check Calcs...', 122, ...
        'Sweep parameter expressions across their input ranges to check the values they produce (Ctrl+Shift+K).', ...
        @() obj.onOpenCheckCalculationsDialog());
    obj.BtnShowDependencies = addButton_('Dependencies...', 132, ...
        'Plot the graph of parameters whose expressions reference other parameters (Ctrl+Shift+G).', ...
        @() obj.onShowParameterDependencyGraph());

    addSeparator_();

    obj.BtnFindReplace = addButton_('Find/Replace...', 130, ...
        'Rename parameters in bulk with a preview of every affected name (Ctrl+H).', ...
        @() obj.onFindReplaceParameterNames());
    obj.BtnShortcuts = addButton_('Shortcuts', 98, ...
        'List every Protocol Designer keyboard shortcut (Ctrl+Shift+?).', ...
        @() obj.showKeyboardShortcuts());

    function button = addButton_(label, width, tooltip, callback)
    % Place the next button at the cursor and advance it past the button.
        button = uibutton(obj.ToolbarPanel, 'push', ...
            'Text', label, ...
            'Position', [cursorX 8 width 30], ...
            'FontWeight', 'bold', ...
            'Tooltip', tooltip, ...
            'ButtonPushedFcn', @(~, ~) callback());
        cursorX = cursorX + width + 6;
    end

    function addSeparator_()
    % Draw a hairline between button groups and advance the cursor past it.
        uipanel(obj.ToolbarPanel, ...
            'Position', [cursorX + 4 10 1 26], ...
            'BackgroundColor', [0.76 0.80 0.85], ...
            'BorderType', 'none');
        cursorX = cursorX + 17;
    end
end
