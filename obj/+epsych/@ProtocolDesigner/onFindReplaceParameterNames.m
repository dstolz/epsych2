function onFindReplaceParameterNames(obj)
% onFindReplaceParameterNames(obj)
% Open the Find and Replace dialog for parameter names (Ctrl+H).
%
% Every change is previewed before it is applied, because a rename also rewrites
% the expressions that referenced the old name and there is no undo.
    if ~isempty(obj.FindReplaceFigure) && isvalid(obj.FindReplaceFigure)
        figure(obj.FindReplaceFigure);
        obj.refreshFindReplacePreview();
        return
    end

    dlgSize = [700 510];
    figPos = obj.Figure.Position;
    dlgPos = [figPos(1) + round((figPos(3) - dlgSize(1)) / 2), ...
              figPos(2) + round((figPos(4) - dlgSize(2)) / 2), ...
              dlgSize];

    obj.FindReplaceFigure = uifigure( ...
        'Name', 'Find and Replace Parameter Names', ...
        'Position', dlgPos, ...
        'Color', [0.945 0.951 0.960], ...
        'Resize', 'off');

    dialog = obj.FindReplaceFigure;

    uilabel(dialog, 'Text', 'Find what', 'Position', [20 468 90 22], ...
        'FontWeight', 'bold', 'FontColor', [0.22 0.28 0.36]);
    obj.FindReplaceFind = uieditfield(dialog, 'text', ...
        'Position', [112 466 348 26], ...
        'Value', obj.ParamNameFilter, ...
        'Tooltip', 'Text to look for inside each parameter name.', ...
        'ValueChangedFcn', @(~, ~) obj.refreshFindReplacePreview());
    obj.FindReplaceFind.ValueChangingFcn = @(~, ~) obj.refreshFindReplacePreview();

    uilabel(dialog, 'Text', 'Replace with', 'Position', [20 430 90 22], ...
        'FontWeight', 'bold', 'FontColor', [0.22 0.28 0.36]);
    obj.FindReplaceWith = uieditfield(dialog, 'text', ...
        'Position', [112 428 348 26], ...
        'Tooltip', 'Replacement text. Leave empty to delete the matched text from each name.', ...
        'ValueChangedFcn', @(~, ~) obj.refreshFindReplacePreview());
    obj.FindReplaceWith.ValueChangingFcn = @(~, ~) obj.refreshFindReplacePreview();

    obj.FindReplaceMatchCase = uicheckbox(dialog, ...
        'Text', 'Match case', ...
        'Position', [480 466 190 26], ...
        'Tooltip', 'Compare Find what against parameter names case-sensitively.', ...
        'ValueChangedFcn', @(~, ~) obj.refreshFindReplacePreview());

    obj.FindReplaceWholeName = uicheckbox(dialog, ...
        'Text', 'Match whole name', ...
        'Position', [480 428 190 26], ...
        'Tooltip', 'Replace only names that equal Find what exactly, instead of every partial match.', ...
        'ValueChangedFcn', @(~, ~) obj.refreshFindReplacePreview());

    uilabel(dialog, 'Text', 'Look in', 'Position', [20 392 90 22], ...
        'FontWeight', 'bold', 'FontColor', [0.22 0.28 0.36]);
    obj.FindReplaceScope = uidropdown(dialog, ...
        'Position', [112 390 348 26], ...
        'Items', {'All parameters', 'Parameters shown in the table', 'Selected parameter'}, ...
        'ItemsData', {'all', 'shown', 'selected'}, ...
        'Value', 'all', ...
        'BackgroundColor', [0.997 0.998 0.999], ...
        'Tooltip', 'Restrict the replacement to the rows currently listed in the parameter table, or to the selected row.', ...
        'ValueChangedFcn', @(~, ~) obj.refreshFindReplacePreview());

    obj.FindReplaceSummary = uilabel(dialog, ...
        'Text', 'Enter text to find.', ...
        'Position', [20 356 660 22], ...
        'FontWeight', 'bold', ...
        'FontColor', [0.22 0.28 0.36]);

    obj.FindReplaceTable = uitable(dialog, ...
        'Position', [20 64 660 286], ...
        'ColumnName', {'Interface / Module', 'Current Name', 'New Name', 'Status'}, ...
        'ColumnWidth', {218, 130, 130, 102}, ...
        'ColumnEditable', false, ...
        'ColumnSortable', true);

    uilabel(dialog, ...
        'Text', 'Expressions that reference a renamed parameter are updated automatically.', ...
        'Position', [20 26 400 30], ...
        'FontAngle', 'italic', ...
        'WordWrap', 'on', ...
        'FontColor', [0.36 0.43 0.52]);

    obj.FindReplaceApply = uibutton(dialog, 'push', ...
        'Text', 'Replace All', ...
        'Position', [430 22 130 32], ...
        'FontWeight', 'bold', ...
        'Enable', 'off', ...
        'Tooltip', 'Rename every previewed parameter whose status is Rename.', ...
        'ButtonPushedFcn', @(~, ~) localApplyReplacement_(obj));

    uibutton(dialog, 'push', ...
        'Text', 'Close', ...
        'Position', [570 22 110 32], ...
        'FontWeight', 'bold', ...
        'ButtonPushedFcn', @(~, ~) delete(dialog));

    obj.refreshFindReplacePreview();
end

function localApplyReplacement_(obj)
% Apply the previewed plan and report the outcome in both status areas.
    changes = obj.FindReplaceChanges;
    if isempty(changes) || ~any(strcmp({changes.Status}, 'rename'))
        return
    end

    try
        appliedCount = obj.applyParameterNameReplacement(changes);
    catch ME
        obj.setStatus(ME.message, 'Adjust the replacement text so every new name is valid and unique.');
        uialert(obj.FindReplaceFigure, ME.message, 'Rename failed');
        obj.refreshFindReplacePreview();
        return
    end

    obj.setStatus(sprintf('Renamed %d parameter(s)', appliedCount), ...
        'Review any expressions that used the old names, then compile to confirm the trials.');
    obj.refreshFindReplacePreview();
    obj.FindReplaceSummary.Text = sprintf('Renamed %d parameter(s).', appliedCount);
end
