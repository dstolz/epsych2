function showKeyboardShortcuts(obj)
% showKeyboardShortcuts(obj)
% Display available keyboard shortcuts in a modal dialog.
    msg = sprintf(['Protocol Designer Keyboard Shortcuts\n\n' ...
                   'TYPE SHORTCUTS:\n' ...
                   '  Ctrl+1    Float\n' ...
                   '  Ctrl+2    Integer\n' ...
                   '  Ctrl+3    Boolean\n' ...
                   '  Ctrl+4    Buffer\n' ...
                   '  Ctrl+5    Coefficient Buffer\n' ...
                   '  Ctrl+6    String\n' ...
                   '  Ctrl+7    File\n' ...
                   '  Ctrl+8    StimType\n' ...
                   '  Ctrl+9    Undefined\n\n' ...
                   'FIND PARAMETERS:\n' ...
                   '  Ctrl+F    Focus the Find box (name filter)\n' ...
                   '  Ctrl+H    Find and replace in parameter names\n\n' ...
                   'ADD PARAMETER:\n' ...
                   '  Ctrl+Shift+B    Add boolean parameter\n' ...
                   '  Ctrl+Shift+T    Add boolean parameter with trigger=true\n' ...
                   '  Ctrl+Shift+F    Add float parameter\n' ...
                   '  Ctrl+Shift+N    Add integer parameter\n\n' ...
                   'PROTOCOL ACTIONS:\n' ...
                   '  Ctrl+S    Save current file\n' ...
                   '  Ctrl+Shift+S    Save As new file\n' ...
                   '  Ctrl+Shift+C    Compile protocol\n' ...
                   '  Ctrl+Shift+V    Open compiled preview dialog\n' ...
                   '  Ctrl+Shift+K    Open check calculations dialog\n' ...
                   '  Ctrl+Shift+G    Plot parameter dependency graph\n' ...
                   '  Ctrl+Shift+O    Open options dialog\n\n' ...
                   'INTERFACE/MODULE:\n' ...
                   '  Ctrl+Shift+I    Open interfaces dialog\n' ...
                   '  Ctrl+Shift+A    Add interface\n' ...
                   '  Ctrl+Shift+M    Add module\n' ...
                   '  Ctrl+Shift+R    Remove parameter\n\n' ...
                   'COLOR MODE:\n' ...
                   '  Ctrl+Shift+Y    Cycle Color By setting\n\n' ...
                   'DETAILS/VIEW:\n' ...
                   '  Ctrl+Shift+D    Open details for selected parameter\n' ...
                   '  Ctrl+Shift+L    Toggle simple/detailed parameter view\n\n' ...
                   'HELP:\n' ...
                   '  Ctrl+Shift+?    Show this keyboard shortcuts help']);

    parentPos = obj.Figure.Position;
    dlgWidth = 520;
    dlgHeight = 580;
    dlgPos = [parentPos(1) + round((parentPos(3) - dlgWidth) / 2), ...
              parentPos(2) + round((parentPos(4) - dlgHeight) / 2), ...
              dlgWidth, dlgHeight];

    dlg = uifigure( ...
        'Name', 'Keyboard Shortcuts', ...
        'Position', dlgPos, ...
        'Resize', 'off', ...
        'WindowStyle', 'modal');

    uitextarea(dlg, ...
        'Value', strsplit(msg, '\n'), ...
        'Editable', 'off', ...
        'Position', [10 50 dlgWidth-20 dlgHeight-70], ...
        'FontSize', 10, ...
        'FontName', 'Courier New', ...
        'BackgroundColor', dlg.Color);

    uibutton(dlg, 'push', ...
        'Text', 'Close', ...
        'Position', [dlgWidth/2-50 10 100 30], ...
        'ButtonPushedFcn', @(~, ~) close(dlg));
end