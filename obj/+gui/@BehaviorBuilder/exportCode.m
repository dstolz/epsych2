function exportCode(obj)
% exportCode(obj)
% Interactive export: validate, save the .eblt first (export implies save,
% so code and spec never diverge), pick the .m target, reconcile class/file
% names, guard overwrites (louder when the target lacks the generated-by
% header), write, and warn when the folder is not on the MATLAB path.

try
    obj.Spec = gui.BehaviorBuilder.specValidate(obj.Spec);
catch ME
    vprintf(0,1,ME)
    uialert(obj.Fig, sprintf('The layout is not complete:\n%s', ME.message), ...
        'Cannot export');
    return
end
if isempty(obj.Spec.Regions)
    uialert(obj.Fig, 'Place at least one component on the canvas first.', ...
        'Nothing to export', 'Icon','info');
    return
end

if ~obj.saveSpec(false), return, end

seed = fullfile(fileparts(obj.SpecFile), [obj.Spec.ClassName '.m']);
[f,p] = uiputfile({'*.m','MATLAB class file (*.m)'}, 'Export GUI Code', seed);
if isequal(f, 0), return, end
mFile = fullfile(p, f);

% MATLAB requires file name == class name; offer the rename rather than fail
[~, base] = fileparts(mFile);
if ~strcmp(base, obj.Spec.ClassName)
    if ~isvarname(base)
        uialert(obj.Fig, sprintf('"%s" is not a valid MATLAB class name.', base), ...
            'Invalid file name');
        return
    end
    sel = uiconfirm(obj.Fig, ...
        sprintf('The file name "%s.m" does not match the class name "%s".\nRename the class to "%s"?', ...
        base, obj.Spec.ClassName, base), 'Class name', ...
        'Options',{'Rename class','Cancel'}, 'DefaultOption','Rename class');
    if ~strcmp(sel, 'Rename class'), return, end
    obj.setSpecField_('ClassName', base);
    obj.refreshSettings_;
    if ~obj.saveSpec(false), return, end % keep the saved spec in step
end

if isfile(mFile)
    txt = fileread(mFile);
    if contains(txt, 'generated by gui.BehaviorBuilder')
        msg = sprintf('Overwrite the existing generated file?\n%s', mFile);
        icon = 'question';
    else
        msg = sprintf(['The existing file was NOT generated by the builder ' ...
            '- overwriting discards its hand-written content.\n%s'], mFile);
        icon = 'warning';
    end
    sel = uiconfirm(obj.Fig, msg, 'File exists', ...
        'Options',{'Overwrite','Cancel'}, 'DefaultOption','Cancel', 'Icon',icon);
    if ~strcmp(sel, 'Overwrite'), return, end
end

try
    gui.BehaviorBuilder.writeCode(obj.Spec, obj.SpecFile, mFile);
catch ME
    vprintf(0,1,ME)
    uialert(obj.Fig, sprintf('Export failed:\n%s', ME.message), 'Export failed');
    return
end

folder = fileparts(mFile);
onPath = any(strcmpi(strsplit(path, pathsep), folder));
if onPath
    uialert(obj.Fig, sprintf(['Generated %s.\n\nPoint a project at it via ' ...
        'Subjects > Subjects & Projects, Project > Edit Project..., ' ...
        'Behavior GUI = "%s".'], mFile, obj.Spec.ClassName), ...
        'Export complete', 'Icon','success');
else
    uialert(obj.Fig, sprintf(['Generated %s.\n\nThat folder is not on the ' ...
        'MATLAB path, so sessions cannot launch the GUI yet. Add it with:' ...
        '\n\n  addpath(''%s'')'], mFile, folder), ...
        'Folder not on path', 'Icon','warning');
end
end
