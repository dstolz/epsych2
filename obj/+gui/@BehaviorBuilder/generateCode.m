function code = generateCode(spec, specFile)
% code = gui.BehaviorBuilder.generateCode(spec, specFile)
% Emit the source of a gui.BehaviorGUI subclass for a layout spec, as a cell
% array of lines (no trailing newlines). specFile is the .eblt path recorded
% in the header and the LayoutSpecFile constant; '' is allowed for previews.
%
% The emitted build() targets only the documented BehaviorGUI helper API plus
% guarded, registered native constructions, so the generated GUI tolerates
% the SelfTest I6 empty-runtime launch exactly like a hand-written subclass.
% Never emit destructor, closeGUI, listener, or watchedHandles code: the base
% class owns lifecycle and teardown.

arguments
    spec struct
    specFile (1,:) char = ''
end

spec = gui.BehaviorBuilder.specValidate(spec);
cls = spec.ClassName;

% reading order: top-left to bottom-right, so the file scans like the window
R = spec.Regions;
if ~isempty(R)
    ord = sortrows([cellfun(@(v) v(1), {R.Row}); cellfun(@(v) v(1), {R.Col}); 1:numel(R)]');
    R = R(ord(:,3));
end

% PreferenceTag uniquing: if a component class is placed more than once, every
% instance gets an explicit tag (deterministic, no "which came first")
emitClasses = cell(1,numel(R));
for i = 1:numel(R)
    emitClasses{i} = gui.BehaviorBuilder.catalogEntry(R(i).Type).EmitClass;
end
needsTag = false(1,numel(R));
for i = 1:numel(R)
    c = emitClasses{i};
    needsTag(i) = ~isempty(c) && sum(strcmp(emitClasses, c)) > 1;
end

L = {};
add('classdef %s < gui.BehaviorGUI', cls);
add('    %%%s Behavior GUI generated by gui.BehaviorBuilder.', upper(cls));
add('    %%   Generated %s from layout spec:', char(datetime('now','Format','yyyy-MM-dd')));
add('    %%     %s', orNone(specFile));
add('    %%   Protocol: %s', orNone(spec.ProtocolPath));
add('    %   Re-open the spec in gui.BehaviorBuilder to modify the layout, or');
add('    %   edit this file directly (hand edits are not reflected in the spec).');
add('    %');
add('    % See also gui.BehaviorGUI, gui.BehaviorBuilder');
add('');
add('    properties (Constant, Hidden)');
add('        % Path of the .eblt layout spec this file was generated from.');
add('        LayoutSpecFile = %s', q(specFile));
add('    end');
add('');
add('    methods');
add('        function obj = %s(RUNTIME)', cls);
add('            obj@gui.BehaviorGUI(RUNTIME, Name=%s, ...', q(spec.WindowName));
add('                DefaultPosition=[100 100 %g %g]);', spec.DefaultSize(1), spec.DefaultSize(2));
add('            if nargout == 0, clear obj; end');
add('        end');
add('    end');
add('');
add('    methods (Access = protected)');

% --- createPsych ---------------------------------------------------------
if ~strcmp(spec.Psych.Type, 'none')
    vn = snapValidName(spec, spec.Psych.Parameter);
    add('        function p = createPsych(obj, R)');
    add('            %% %s analysis on ''%s''; the GUI''s NewData listener follows', ...
        spec.Psych.Type, spec.Psych.Parameter);
    add('            % p.Events when this returns a valid object.');
    add('            p = [];');
    add('            if isfield(obj.P, %s)', q(vn));
    switch spec.Psych.Type
        case 'Staircase'
            add('                p = psychophysics.Staircase(R, obj.P.%s);', vn);
        case 'Detection'
            if isempty(spec.Psych.TargetTrialType)
                add('                p = psychophysics.Detection(R, obj.P.%s);', vn);
            else
                add('                p = psychophysics.Detection(R, obj.P.%s, epsych.BitMask.%s);', ...
                    vn, spec.Psych.TargetTrialType);
            end
    end
    add('            end');
    add('        end');
    add('');
end

% --- build ---------------------------------------------------------------
add('        function build(obj, fig)');
add('            g = uigridlayout(fig, [%d %d]);', spec.Grid.Rows, spec.Grid.Cols);
add('            g.RowHeight   = %s;', fmtSizes(spec.Grid.RowHeight));
add('            g.ColumnWidth = %s;', fmtSizes(spec.Grid.ColumnWidth));

for i = 1:numel(R)
    r = R(i);
    tag = '';
    if needsTag(i), tag = sprintf('%s_%s', cls, r.Id); end
    add('');
    disp_ = gui.BehaviorBuilder.catalogEntry(r.Type).Display;
    if isempty(r.Label) || strcmp(r.Label, disp_)
        add('            %% --- %s ---', disp_);
    else
        add('            %% --- %s (%s) ---', r.Label, disp_);
    end
    L = [L, emitRegion(r, i, tag)]; %#ok<AGROW>
end

add('        end');
add('    end');
add('end');
code = L;

    function add(fmt, varargin)
        if nargin == 1
            L{end+1} = fmt;
        else
            L{end+1} = sprintf(fmt, varargin{:});
        end
    end
end

% =========================================================================
function lines = emitRegion(r, i, tag)
% One region's build() lines. Panel-hosted components share the host/pop-out
% scaffolding; layout-level types (control column, button row, session clock,
% screen capture, staircase axes) emit their own.
o = r.Options;
lines = {};

switch r.Type
    case 'ControlColumn'
        args = {sprintf('Title=%s', q(r.Label)), ...
                sprintf('Row=%s', fmtSpan(r.Row)), sprintf('Column=%s', fmtSpan(r.Col))};
        out('col%d = obj.controlColumn(g, %s);', i, strjoin(args, ', '));
        anyUpdatable = false;
        for k = 1:numel(o.Controls)
            c = o.Controls(k);
            nv = {};
            if ~strcmp(c.Type,'auto'), nv{end+1} = sprintf('Type=%s', q(c.Type)); end %#ok<AGROW>
            if c.autoCommit,           nv{end+1} = 'autoCommit=true'; end %#ok<AGROW>
            if ~isempty(c.Text),       nv{end+1} = sprintf('Text=%s', q(c.Text)); end %#ok<AGROW>
            s = sprintf('obj.addControl(col%d, %s', i, q(c.Param));
            if ~isempty(nv), s = [s ', ' strjoin(nv, ', ')]; end %#ok<AGROW>
            out('%s);', s);
            anyUpdatable = anyUpdatable || (~c.autoCommit && ~strcmp(c.Type,'readonly'));
        end
        if anyUpdatable
            out('obj.addUpdateButton(col%d); %% commits every control above', i);
        end

    case 'ButtonRow'
        n = numel(o.Buttons) + double(o.IncludeScreenCapture);
        out('row%d = uigridlayout(g, [1 %d]);', i, max(n,1));
        out('row%d.Layout.Row = %s; row%d.Layout.Column = %s;', ...
            i, fmtSpan(r.Row), i, fmtSpan(r.Col));
        for k = 1:numel(o.Buttons)
            b = o.Buttons(k);
            if isempty(b.Text)
                out('obj.addButton(row%d, %s);', i, q(b.Param));
            else
                out('obj.addButton(row%d, %s, Text=%s);', i, q(b.Param), q(b.Text));
            end
        end
        if o.IncludeScreenCapture
            out('obj.add(''gui.components.ScreenCapture'', row%d);', i);
        end

    case 'Monitor'
        [host, popParent] = emitHost(r, i);
        args = {fmtCellstr(o.Params), sprintf('pollPeriod=%s', mat2str(o.PollPeriod)), ...
                sprintf('type="%s"', o.Style)};
        if ~isempty(tag), args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
        emitHelperCall(r, i, popParent, sprintf('obj.add(''gui.components.Parameter_Monitor'', %s, ''Parameters'', %s)', host, strjoin(args, ', ')));

    case 'NextTrial'
        [host, popParent] = emitHost(r, i);
        emitHelperCall(r, i, popParent, sprintf('obj.add(''gui.components.NextTrial'', %s%s)', host, tagArg(tag)));

    case 'Performance'
        [host, popParent] = emitHost(r, i);
        emitHelperCall(r, i, popParent, sprintf('obj.add(''gui.components.SessionPerformance'', %s%s)', host, tagArg(tag)));

    case 'Scatter'
        [host, popParent] = emitHost(r, i);
        args = {};
        if ~isempty(o.XParameter),     args{end+1} = sprintf('XParameter=%s', q(o.XParameter)); end
        if ~isempty(o.YParameter),     args{end+1} = sprintf('YParameter=%s', q(o.YParameter)); end
        if ~isempty(o.ColorParameter), args{end+1} = sprintf('ColorParameter=%s', q(o.ColorParameter)); end
        if ~isempty(tag),              args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
        s = sprintf('h%d = gui.components.ParameterScatter(obj.RUNTIME, %s', i, host);
        if ~isempty(args), s = [s ', ' strjoin(args, ', ')]; end
        out('%s);', s);
        out('obj.register(h%d);', i);
        emitPopOut(r, popParent, sprintf('h%d', i), false);

    case 'History'
        [host, popParent] = emitHost(r, i);
        out('if ~isempty(obj.Psych) && isvalid(obj.Psych)');
        out('    h%d = gui.components.History(obj.Psych, %s%s);', i, host, tagArg(tag));
        out('    obj.register(h%d);', i);
        emitPopOut(r, popParent, sprintf('h%d', i), true);
        out('end');

    case 'PsychPlot'
        [host, popParent] = emitHost(r, i);
        out('if ~isempty(obj.Psych) && isvalid(obj.Psych)');
        out('    ax%d = axes(%s); %% classic axes: gui.components.PsychPlot requires one', i, host);
        out('    h%d = gui.components.PsychPlot(obj.Psych, ax%d);', i, i);
        out('    obj.register(h%d);', i);
        emitPopOut(r, popParent, sprintf('h%d', i), true);
        out('end');

    case 'StaircasePlot'
        if r.PopOut
            [host, popParent] = emitHost(r, i);
            out('ax%d = uiaxes(%s);', i, host);
            out('if ~isempty(obj.Psych) && isvalid(obj.Psych)');
            out('    obj.Psych.Plot(ax%d);', i);
            out('    obj.addPopOutButton(%s, obj.Psych);', popParent);
            out('end');
        else
            out('ax%d = uiaxes(g);', i);
            out('ax%d.Layout.Row = %s; ax%d.Layout.Column = %s;', ...
                i, fmtSpan(r.Row), i, fmtSpan(r.Col));
            out('if ~isempty(obj.Psych) && isvalid(obj.Psych)');
            out('    obj.Psych.Plot(ax%d);', i);
            out('end');
        end

    case 'SlidingWindow'
        host = emitHost(r, i); % never poppable, so there is no pop-out parent
        out('if ~isempty(obj.Psych) && isvalid(obj.Psych)');
        out('    ax%d = axes(%s); %% classic axes: the plot requires one', i, host);
        out('    h%d = gui.components.SlidingWindowPerformancePlot(obj.Psych, ax%d);', i, i);
        out('    obj.register(h%d);', i);
        out('end');

    case 'OnlinePlot'
        host = emitHost(r, i); % never poppable, so there is no pop-out parent
        out('ax%d = axes(%s); %% classic axes: gui.components.OnlinePlot requires one', i, host);
        out('h%d = gui.components.OnlinePlot(obj.RUNTIME, %s, ax%d);', i, fmtCellstr(o.Source), i);
        out('obj.register(h%d);', i);

    case 'BufferPlot'
        [host, popParent] = emitHost(r, i);
        args = {};
        if ~isempty(o.Buffers),   args{end+1} = sprintf('Buffers=%s', fmtCellstr(o.Buffers)); end
        % mat2str, not %g: %g keeps 6 significant digits, and the TDT rates
        % this field holds (24414.0625, 97656.25) would bake in wrong.
        if o.SampleRate > 0,      args{end+1} = sprintf('SampleRate=%s', mat2str(o.SampleRate)); end
        if ~isempty(o.Layout),    args{end+1} = sprintf('Layout=%s', q(o.Layout)); end
        if o.NumTrialsShown > 1,  args{end+1} = sprintf('NumTrialsShown=%d', o.NumTrialsShown); end
        if ~isempty(tag),         args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
        s = sprintf('h%d = gui.components.BufferPlot(obj.RUNTIME, %s', i, host);
        if ~isempty(args), s = [s ', ' strjoin(args, ', ')]; end
        out('%s);', s);
        out('obj.register(h%d);', i);
        emitPopOut(r, popParent, sprintf('h%d', i), false);

    case 'SessionClock'
        out('h%d = gui.components.SessionClock(g%s);', i, tagArg(tag));
        out('h%d.PanelH.Layout.Row = %s; h%d.PanelH.Layout.Column = %s;', ...
            i, fmtSpan(r.Row), i, fmtSpan(r.Col));
        out('h%d.attachRuntime(obj.RUNTIME);', i);
        out('h%d.start();', i);
        out('obj.register(h%d);', i);

    case 'TrialTimer'
        emitPanel(r, i);
        out('h%d = gui.components.ElapsedTrialTimer(pnl%d);', i, i);
        out('h%d.attachRuntime(obj.RUNTIME);', i);
        out('obj.register(h%d);', i);

    case 'ModeIndicator'
        emitPanel(r, i);
        out('h%d = gui.components.ModeIndicator(pnl%d);', i, i);
        out('h%d.attachRuntime(obj.RUNTIME);', i);
        out('obj.register(h%d);', i);

    case 'Notes'
        if o.ButtonOnly
            % One button in the cell; the notes live in the window it opens,
            % which is its own pop-out — hence no addPopOutButton here.
            out('nb%d = uigridlayout(g, [1 1]);', i);
            out('nb%d.Layout.Row = %s; nb%d.Layout.Column = %s;', ...
                i, fmtSpan(r.Row), i, fmtSpan(r.Col));
            args = {sprintf('Text=%s', q(o.Text))};
            if ~strcmp(o.TimeStamp,'elapsed')
                args{end+1} = sprintf('TimeStamp="%s"', o.TimeStamp);
            end
            if ~isempty(tag), args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
            out('obj.add(''gui.components.Notes'', nb%d, ''ButtonOnly'', true, %s);', i, strjoin(args, ', '));
        else
            [host, popParent] = emitHost(r, i);
            args = {};
            if ~strcmp(o.TimeStamp,'elapsed')
                args{end+1} = sprintf('TimeStamp="%s"', o.TimeStamp);
            end
            if o.Editable, args{end+1} = 'Editable=true'; end
            if ~isempty(tag), args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
            s = sprintf('obj.add(''gui.components.Notes'', %s', host);
            if ~isempty(args), s = [s ', ' strjoin(args, ', ')]; end
            s = [s ')'];
            emitHelperCall(r, i, popParent, s);
        end

    case 'SyringePump'
        [host, popParent] = emitHost(r, i);
        args = {};
        if ~isempty(o.Sections)
            args{end+1} = sprintf('Sections=%s', fmtStringArray(o.Sections));
        end
        if ~isempty(tag), args{end+1} = sprintf('PreferenceTag=%s', q(tag)); end
        s = sprintf('obj.add(''gui.components.SyringePump'', %s', host);
        if ~isempty(args), s = [s ', ' strjoin(args, ', ')]; end
        s = [s ')'];
        emitHelperCall(r, i, popParent, s);

    case 'ScreenCapture'
        out('sc%d = uigridlayout(g, [1 1]);', i);
        out('sc%d.Layout.Row = %s; sc%d.Layout.Column = %s;', ...
            i, fmtSpan(r.Row), i, fmtSpan(r.Col));
        out('obj.add(''gui.components.ScreenCapture'', sc%d);', i);

    case 'SessionGate'
        % The button is only half of it: waitForSessionGate in the
        % constructor is what actually holds the session, and the generated
        % class does not write a constructor. The comment is the handoff.
        out('sg%d = uigridlayout(g, [1 1]);', i);
        out('sg%d.Layout.Row = %s; sg%d.Layout.Column = %s;', ...
            i, fmtSpan(r.Row), i, fmtSpan(r.Col));
        out('%% Add "obj.waitForSessionGate();" to a constructor of your own');
        out('%% to make the session hold here until this button is pressed.');
        out('obj.add(''gui.components.SessionGate'', sg%d, Text=%s);', i, q(o.Text));

    case 'PhaseSelector'
        emitPanel(r, i);
        if isempty(o.PhasePath)
            out('ps%d = gui.components.PhaseSelector(obj.RUNTIME);', i);
        else
            out('ps%d = gui.components.PhaseSelector(obj.RUNTIME, %s);', i, q(o.PhasePath));
        end
        out('ps%d.createGUI(pnl%d);', i, i);
        out('obj.register(ps%d);', i);

    case 'StatusBar'
        emitPanel(r, i);
        out('h%d = gui.components.StatusBar(pnl%d, InitialText=%s);', i, i, q(o.InitialText));
        out('obj.register(h%d);', i);

    case 'FilenameField'
        emitPanel(r, i);
        out('h%d = gui.components.FilenameValidator(obj.RUNTIME, pnl%d, %s);', ...
            i, i, q(o.DefaultFilename));
        out('obj.register(h%d);', i);

    otherwise
        % A component with no hand-written branch above: everything needed
        % to place it is in its own gui.ComponentSpec, so one generic
        % emitter serves every component added from now on. The branches
        % above are kept only because saved .eblt specs already use their
        % option field names.
        emitGeneric(r, i, tag);
end

    function emitGeneric(rr, ii, tg)
        % obj.add(...) for a discovered component, driven by its spec.
        s = gui.ComponentSpec.forClass(gui.BehaviorBuilder.classForType_(rr.Type));
        if isempty(s.className)
            error('epsych:BehaviorBuilder:BadRegion', ...
                'No emitter and no component class for type "%s"', rr.Type)
        end

        % A component that takes a container gets the usual titled panel; one
        % that only wants an axes gets the panel and lets add make the axes
        % inside it.
        if any(s.shape == "parent")
            [host, popParent] = emitHost(rr, ii);
        else
            emitPanel(rr, ii);
            host = sprintf('pnl%d', ii);
            popParent = '';
            if rr.PopOut
                [host, popParent] = emitHost(rr, ii);
            end
        end

        args = {};
        fn = fieldnames(rr.Options);
        for k = 1:numel(fn)
            v = rr.Options.(fn{k});
            [d, hasD] = s.optionDefault(fn{k});
            if hasD && isequal(v, d), continue; end   % never emit a default
            args{end+1} = sprintf('%s=%s', fn{k}, fmtLiteral(v)); %#ok<AGROW>
        end
        if ~isempty(tg)
            args{end+1} = sprintf('PreferenceTag=%s', q(tg));
        end

        call = sprintf('obj.add(%s, %s', q(s.className), host);
        if ~isempty(args), call = [call ', ' strjoin(args, ', ')]; end
        call = [call ')'];
        emitHelperCall(rr, ii, popParent, call);
    end

    function out(fmt, varargin)
        lines{end+1} = ['            ' sprintf(fmt, varargin{:})];
    end

    function emitPanel(rr, ii)
        if isempty(rr.Label)
            out('pnl%d = uipanel(g);', ii);
        else
            out('pnl%d = uipanel(g, ''Title'', %s);', ii, q(rr.Label));
        end
        out('pnl%d.Layout.Row = %s; pnl%d.Layout.Column = %s;', ...
            ii, fmtSpan(rr.Row), ii, fmtSpan(rr.Col));
    end

    function [host, popParent] = emitHost(rr, ii)
        % Titled panel in the grid cell; with a pop-out, an inner 2-row grid
        % holds the component (borderless panel) above the button.
        emitPanel(rr, ii);
        if rr.PopOut
            out('in%d = uigridlayout(pnl%d, [2 1]);', ii, ii);
            out('in%d.RowHeight = {''1x'',26}; in%d.Padding = [0 0 0 0];', ii, ii);
            out('hp%d = uipanel(in%d, ''BorderType'',''none'');', ii, ii);
            host = sprintf('hp%d', ii);
            popParent = sprintf('in%d', ii);
        else
            host = sprintf('pnl%d', ii);
            popParent = '';
        end
    end

    function emitPopOut(rr, popParent, hVar, insideGuard)
        if ~rr.PopOut, return, end
        ind = '';
        if insideGuard, ind = '    '; end
        out('%sif ~isempty(%s), obj.addPopOutButton(%s, %s); end', ...
            ind, hVar, popParent, hVar);
    end

    function emitHelperCall(rr, ii, popParent, callExpr)
        % Helper-API component: capture the handle only when the pop-out
        % button needs it, so the generated file stays lint-clean.
        if rr.PopOut
            out('h%d = %s;', ii, callExpr);
            emitPopOut(rr, popParent, sprintf('h%d', ii), false);
        else
            out('%s;', callExpr);
        end
    end
end

% =========================================================================
function s = q(c)
% Quoted char literal, embedded quotes doubled (names come from protocols).
s = ['''' strrep(char(c), '''', '''''') ''''];
end

function s = orNone(c)
if isempty(c), s = '(none)'; else, s = c; end
end

function s = tagArg(tag)
% ', PreferenceTag=...' suffix for helper calls; '' when no tag is needed.
if isempty(tag)
    s = '';
else
    s = sprintf(', PreferenceTag=%s', q(tag));
end
end

function s = fmtSpan(v)
if v(1) == v(2)
    s = sprintf('%d', v(1));
else
    s = sprintf('[%d %d]', v(1), v(2));
end
end

function s = fmtSizes(c)
% {'60','1x'} -> "{60, '1x'}"
parts = cell(1,numel(c));
for k = 1:numel(c)
    if isempty(regexp(c{k}, 'x$', 'once'))
        parts{k} = c{k};                 % pixel count: emit as a number
    else
        parts{k} = ['''' c{k} ''''];     % weight: emit as a char
    end
end
s = ['{' strjoin(parts, ', ') '}'];
end

function s = fmtCellstr(c)
parts = cellfun(@(x) q(x), c, 'uni', 0);
s = ['{' strjoin(parts, ',') '}'];
end

function s = fmtStringArray(c)
parts = cellfun(@(x) ['"' strrep(char(x),'"','""') '"'], c, 'uni', 0);
s = ['[' strjoin(parts, ' ') ']'];
end

function vn = snapValidName(spec, name)
% obj.P is keyed by validName; the spec stores display Names. Resolve through
% the snapshot, falling back to makeValidName for hand-built specs.
snap = spec.ParameterSnapshot;
ix = find(strcmp({snap.Name}, name), 1);
if ~isempty(ix)
    vn = snap(ix).validName;
else
    vn = matlab.lang.makeValidName(name);
end
end

function s = fmtLiteral(v)
% MATLAB source for an option value of any of the shapes a spec option can
% hold. Used only by the generic emitter; the hand-written branches format
% their own values because they know exactly which shape each one is.
if ischar(v)
    s = q(v);
elseif isstring(v) && isscalar(v)
    s = sprintf('"%s"', char(v));
elseif isstring(v)
    s = fmtStringArray(v);
elseif iscell(v)
    s = fmtCellstr(v);
elseif islogical(v)
    if v, s = 'true'; else, s = 'false'; end
else
    % mat2str, not %g: %g keeps 6 significant digits, and a TDT sample rate
    % (24414.0625) would bake in wrong.
    s = mat2str(v);
end
end
