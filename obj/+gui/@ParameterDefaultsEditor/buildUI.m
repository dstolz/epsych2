function buildUI(self, visible)
% buildUI(self, visible)
% Build the editor: who and which protocol, a filter strip, the parameter
% table, the copy and clear actions, Save/Cancel, and a status line.
%
% The table puts the protocol's value and range BESIDE the editable columns,
% because a default is only meaningful as a departure from them: an operator
% deciding a start depth wants to see the protocol's start and the range it
% must fall in without opening the designer. Cells that cannot take a value (a
% randomized parameter's Default, a Boolean's Min/Max) are greyed rather than
% hidden, so every row reads the same way across.
%
% See also: gui.ParameterDefaultsEditor
arguments
    self
    visible (1,1) logical = true
end

pos = gui.BehaviorGUI.getSavedFigurePosition(self.PREF_TAG, self.DEFAULT_POSITION);

f = uifigure('Name', sprintf('Parameter Defaults — %s in %s', self.SubjectName, self.ProjectName), ...
    'Tag', self.FIGURE_TAG, ...
    'Position', pos, ...
    'Visible', matlab.lang.OnOffSwitchState(visible), ...
    'WindowKeyPressFcn', @(~, evt) self.onKey_(evt));
f.UserData = self;
f.CloseRequestFcn = @(~, ~) self.close();
self.H.figure = f;

g = uigridlayout(f, [6 1]);
g.RowHeight = {24, 'fit', 26, '1x', 30, 20};
g.Padding = [12 10 12 8];
g.RowSpacing = 8;

% ---------- Row 1-2: whose defaults, and against which protocol ----------
uilabel(g, 'Text', sprintf('%s  ·  %s', self.SubjectName, self.ProjectName), ...
    'FontWeight', 'bold', 'FontSize', 14);

self.H.info = uilabel(g, 'WordWrap', 'on', 'FontColor', self.MUTED, ...
    'Text', sprintf(['%s\nA value here replaces the protocol''s for this subject every time ' ...
        'Run or Preview is pressed. Leave a cell blank to use the protocol''s. Min and Max ' ...
        'widen or narrow the range for this subject; a randomized parameter takes those only.'], ...
        self.ProtocolText));

% ---------- Row 3: filter strip -----------------------------------------
gFilter = uigridlayout(g, [1 4]);
gFilter.ColumnWidth = {'1x', 190, 170, 190};
gFilter.Padding = [0 0 0 0];
gFilter.ColumnSpacing = 8;

% Filtered as the operator types; a plain case-insensitive contains, never a
% regex, so typing 'Depth(' narrows the list instead of raising an error.
self.H.filter = uieditfield(gFilter, 'text', 'Placeholder', 'Filter parameters...', ...
    'ValueChangingFcn', @(~, evt) self.onFilterChanging_(evt.Value), ...
    'ValueChangedFcn', @(~, ~) self.onFilterChanged_());
self.H.chkOnlySet = uicheckbox(gFilter, 'Text', 'Only parameters with defaults', ...
    'ValueChangedFcn', @(~, ~) self.repaint_());
self.H.chkHidden = uicheckbox(gFilter, 'Text', 'Show hidden parameters', ...
    'Tooltip', ['Parameters the protocol does not show. They take defaults too: each ' ...
        'run starts them at their first value.'], ...
    'ValueChangedFcn', @(~, ~) self.repaint_());
self.H.count = uilabel(gFilter, 'Text', '', 'HorizontalAlignment', 'right', ...
    'FontColor', self.MUTED);

% ---------- Row 4: the parameters ---------------------------------------
% Not sortable: every callback maps a table row through DisplayIdx_, which is
% the order the rows were written in, not an order a header click could make.
self.H.table = uitable(g, ...
    'ColumnName', {'Parameter', 'Unit', 'Protocol', 'Protocol Range', ...
                   'Default', 'Min', 'Max', 'Notes'}, ...
    'ColumnFormat', {'char', 'char', 'char', 'char', 'char', 'char', 'char', 'char'}, ...
    'ColumnEditable', [false false false false true true true false], ...
    'ColumnWidth', {190, 50, 120, 110, 110, 70, 70, 'auto'}, ...
    'RowName', {}, ...
    'RowStriping', 'off', ...
    'SelectionType', 'row', ...
    'Multiselect', 'on', ...
    'CellEditCallback', @(~, evt) self.onCellEdit_(evt));

% ---------- Row 5: actions ----------------------------------------------
gButtons = uigridlayout(g, [1 7]);
gButtons.ColumnWidth = {130, 180, 110, 90, '1x', 90, 90};
gButtons.Padding = [0 0 0 0];
gButtons.ColumnSpacing = 8;

self.H.btnCopySession = uibutton(gButtons, 'Text', 'Copy from Session', ...
    'Tooltip', ['Take the values and bounds the session holds now for this subject, ' ...
        'wherever they differ from the protocol'], ...
    'ButtonPushedFcn', @(~, ~) self.copyFromSession());
self.H.btnCopyFile = uibutton(gButtons, 'Text', 'Copy from Last Data File...', ...
    'Tooltip', ['Take the values the last trial of this subject''s most recent saved ' ...
        'session recorded, wherever they differ from the protocol'], ...
    'ButtonPushedFcn', @(~, ~) self.onCopyDataFile_());
self.H.btnClear = uibutton(gButtons, 'Text', 'Clear Selected', ...
    'ButtonPushedFcn', @(~, ~) self.onClearSelected_());
self.H.btnClearAll = uibutton(gButtons, 'Text', 'Clear All', ...
    'ButtonPushedFcn', @(~, ~) self.onClearAll_());
uilabel(gButtons, 'Text', '');
self.H.btnSave = uibutton(gButtons, 'Text', 'Save', 'FontWeight', 'bold', ...
    'Tooltip', 'Write these defaults to the roster (Ctrl+S)', ...
    'ButtonPushedFcn', @(~, ~) self.save());
uibutton(gButtons, 'Text', 'Close', ...
    'ButtonPushedFcn', @(~, ~) self.close());

% ---------- Row 6: status line ------------------------------------------
self.H.status = uilabel(g, 'Text', '', 'FontColor', self.MUTED);

end
