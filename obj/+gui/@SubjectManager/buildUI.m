function buildUI(self)
% buildUI(self)
% Build the manager window and every control in it.
%
% A toolbar over three rows: the open roster, the project/subject split, and a
% status line.
% Projects are a uilistbox rather than a uitree -- they are a flat set, and a
% listbox gives arrow-key and type-ahead navigation for free. Subjects are a
% uitable because each row needs its own box assignment before it is committed,
% which neither a checkbox tree nor a listbox can hold.
%
% See also: gui.SubjectManager.refresh, gui.SubjectManager.addToSession
arguments
    self
end

pos = gui.BoxGUI.getSavedFigurePosition(self.PREF_TAG, self.DEFAULT_POSITION);

f = uifigure('Name','Subjects & Projects', 'Tag', self.FIGURE_TAG, ...
    'Position', pos, ...
    'WindowKeyPressFcn', @(~,evt) self.onKeyPress_(evt));
f.UserData = self;
f.CloseRequestFcn = @(~,~) delete(self);
movegui(f, 'onscreen');
self.H.figure = f;

% ---------- Toolbar -----------------------------------------------------
% One-click access to what the menus carry, grouped in the order the work
% happens: the roster file, then projects, then subjects, then membership,
% then the session. It replaces the strip of text buttons that used to run
% across the top -- those four actions are the first group here, and the row
% they occupied now carries only the name of the open roster.
%
% Icons come from gui.toolbarIcon, which draws them as pixel art so the
% window ships no image files. Every tool is switched by updateEnableStates_
% beside the button and menu item for the same action, so the three surfaces
% for one action can never disagree about whether it is available.
tb = uitoolbar(f);
self.H.toolbar = tb;

self.H.tb_refresh = uipushtool(tb, ...
    'Tag','tb_refresh', ...
    'Icon',gui.toolbarIcon("refresh"), ...
    'Tooltip','Refresh: re-read the roster file (F5)', ...
    'ClickedCallback', @(~,~) self.refresh());

self.H.tb_roster_file = uipushtool(tb, ...
    'Tag','tb_roster_file', ...
    'Icon',gui.toolbarIcon("rosterfile"), ...
    'Tooltip','Roster File...: choose or create the roster this window shows', ...
    'ClickedCallback', @(~,~) self.chooseRosterFile_());

self.H.tb_import = uipushtool(tb, ...
    'Tag','tb_import', ...
    'Icon',gui.toolbarIcon("import"), ...
    'Tooltip','Import from Config...: take the subjects out of an existing .ecfg', ...
    'ClickedCallback', @(~,~) self.onImportFromConfig_());

self.H.tb_export = uipushtool(tb, ...
    'Tag','tb_export', ...
    'Icon',gui.toolbarIcon("export"), ...
    'Tooltip','Export CSV...: write the whole roster to a spreadsheet', ...
    'ClickedCallback', @(~,~) self.onExportCsv_());

self.H.tb_new_project = uipushtool(tb, ...
    'Tag','tb_new_project', ...
    'Icon',gui.toolbarIcon("projectnew"), ...
    'Separator','on', ...
    'Tooltip','New Project... (Ctrl+Shift+N)', ...
    'ClickedCallback', @(~,~) self.onNewProject_());

self.H.tb_edit_project = uipushtool(tb, ...
    'Tag','tb_edit_project', ...
    'Icon',gui.toolbarIcon("projectedit"), ...
    'Tooltip','Edit Project...: name, notes, default protocol, data path, box GUI', ...
    'ClickedCallback', @(~,~) self.onEditProject_());

self.H.tb_delete_project = uipushtool(tb, ...
    'Tag','tb_delete_project', ...
    'Icon',gui.toolbarIcon("projectdelete"), ...
    'Tooltip','Delete Project...: its subjects stay in the roster', ...
    'ClickedCallback', @(~,~) self.onDeleteProject_());

self.H.tb_new_subject = uipushtool(tb, ...
    'Tag','tb_new_subject', ...
    'Icon',gui.toolbarIcon("addsubject"), ...
    'Separator','on', ...
    'Tooltip','New Subject... (Ctrl+N)', ...
    'ClickedCallback', @(~,~) self.onNewSubject_());

self.H.tb_edit_subject = uipushtool(tb, ...
    'Tag','tb_edit_subject', ...
    'Icon',gui.toolbarIcon("subjectedit"), ...
    'Tooltip','Edit Subject...: details of the selected row', ...
    'ClickedCallback', @(~,~) self.onEditSubject_());

% Deleting from the roster is the one irreversible action here, so it is
% drawn as a red cross rather than the minus that means "remove from this
% project", and it acts on the selected row rather than on the ticks.
self.H.tb_delete_subject = uipushtool(tb, ...
    'Tag','tb_delete_subject', ...
    'Icon',gui.toolbarIcon("subjectdelete"), ...
    'Tooltip','Delete from Roster...: removes the record entirely (confirmed)', ...
    'ClickedCallback', @(~,~) self.onDeleteSubject_());

self.H.tb_add_to_project = uipushtool(tb, ...
    'Tag','tb_add_to_project', ...
    'Icon',gui.toolbarIcon("addtoproject"), ...
    'Separator','on', ...
    'Tooltip','Add the checked subjects to the selected project', ...
    'ClickedCallback', @(~,~) self.onAddToProject_());

self.H.tb_remove_from_project = uipushtool(tb, ...
    'Tag','tb_remove_from_project', ...
    'Icon',gui.toolbarIcon("removefromproject"), ...
    'Tooltip','Remove the checked subjects from the selected project', ...
    'ClickedCallback', @(~,~) self.onRemoveFromProject_());

% Wears two faces, like the button and the menu item: updateEnableStates_
% swaps the icon and tooltip for Restore when every checked row is retired.
self.H.tb_retire = uipushtool(tb, ...
    'Tag','tb_retire', ...
    'Icon',gui.toolbarIcon("retire"), ...
    'Tooltip','Retire the checked subjects from the selected project', ...
    'ClickedCallback', @(~,~) self.onToggleRetired_());

self.H.tb_set_protocol = uipushtool(tb, ...
    'Tag','tb_set_protocol', ...
    'Icon',gui.toolbarIcon("protocol"), ...
    'Separator','on', ...
    'Tooltip','Set Protocol for Checked...: overrides the remembered protocol', ...
    'ClickedCallback', @(~,~) self.onSetProtocol_(true));

self.H.tb_add_to_session = uipushtool(tb, ...
    'Tag','tb_add_to_session', ...
    'Icon',gui.toolbarIcon("tosession"), ...
    'Tooltip','Add Checked to Session: each gets a free box and its protocol', ...
    'ClickedCallback', @(~,~) self.addToSession());

% ---------- Menus -------------------------------------------------------
mFile = uimenu(f, 'Text','File');
uimenu(mFile, 'Text','&Refresh', 'Accelerator','R', ...
    'MenuSelectedFcn', @(~,~) self.refresh());
uimenu(mFile, 'Text','Roster &File...', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.chooseRosterFile_());
uimenu(mFile, 'Text','&Import from Config...', ...
    'MenuSelectedFcn', @(~,~) self.onImportFromConfig_());
uimenu(mFile, 'Text','&Export CSV...', ...
    'MenuSelectedFcn', @(~,~) self.onExportCsv_());
uimenu(mFile, 'Text','&Close', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) delete(self));

mSubject = uimenu(f, 'Text','Subject');
self.H.mnu_new_subject = uimenu(mSubject, 'Text','&New Subject...', 'Accelerator','N', ...
    'MenuSelectedFcn', @(~,~) self.onNewSubject_());
self.H.mnu_edit_subject = uimenu(mSubject, 'Text','&Edit Subject...', ...
    'MenuSelectedFcn', @(~,~) self.onEditSubject_());
self.H.mnu_add_to_project = uimenu(mSubject, 'Text','&Add to Project', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onAddToProject_());
self.H.mnu_remove_from_project = uimenu(mSubject, 'Text','&Remove from Project', ...
    'MenuSelectedFcn', @(~,~) self.onRemoveFromProject_());
self.H.mnu_retire = uimenu(mSubject, 'Text','Re&tire', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onToggleRetired_());
% Deleting from the roster is menu-only and confirmed. The Delete key is
% bound to Remove from Project, which is the reversible one.
self.H.mnu_delete_subject = uimenu(mSubject, 'Text','&Delete from Roster...', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onDeleteSubject_());

mProject = uimenu(f, 'Text','Project');
uimenu(mProject, 'Text','&New Project...', ...
    'MenuSelectedFcn', @(~,~) self.onNewProject_());
self.H.mnu_edit_project = uimenu(mProject, 'Text','&Edit Project...', ...
    'MenuSelectedFcn', @(~,~) self.onEditProject_());
self.H.mnu_delete_project = uimenu(mProject, 'Text','&Delete Project...', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onDeleteProject_());

% Protocol versions are a project-wide question -- "is everyone on the current
% one?" -- so they get their own menu rather than hiding inside Subject.
mProtocol = uimenu(f, 'Text','Protocol');
self.H.mnu_check_versions = uimenu(mProtocol, 'Text','&Check Protocol Versions', ...
    'MenuSelectedFcn', @(~,~) self.onCheckVersions_());
self.H.mnu_open_designer = uimenu(mProtocol, 'Text','&Open in Protocol Designer', ...
    'MenuSelectedFcn', @(~,~) self.onOpenInDesigner_());
self.H.mnu_update_checked = uimenu(mProtocol, 'Text','&Update Checked to Latest Version', ...
    'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onUpdateProtocol_('checked'));
self.H.mnu_update_project = uimenu(mProtocol, 'Text','Update &All in Project to Latest Version', ...
    'MenuSelectedFcn', @(~,~) self.onUpdateProtocol_('project'));
self.H.mnu_use_default = uimenu(mProtocol, 'Text','Switch Checked to Project &Default Protocol', ...
    'MenuSelectedFcn', @(~,~) self.onUpdateProtocol_('checked', UseProjectDefault = true));
self.H.mnu_revert = uimenu(mProtocol, 'Text','&Revert Protocol Version...', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onRevertProtocol_());

mSession = uimenu(f, 'Text','Session');
self.H.mnu_add_to_session = uimenu(mSession, 'Text','Add &Checked to Session', ...
    'MenuSelectedFcn', @(~,~) self.addToSession());
self.H.mnu_set_protocol = uimenu(mSession, 'Text','Set &Protocol for Checked...', ...
    'MenuSelectedFcn', @(~,~) self.onSetProtocol_(true));

% ---------- Root layout -------------------------------------------------
g = uigridlayout(f, [3 1]);
g.RowHeight = {'fit', '1x', 22};
g.Padding = [10 8 10 8];
g.RowSpacing = 8;

% ---------- Row 1: the open roster --------------------------------------
% Which roster file this window is showing, and whether it is read-only. The
% four buttons that used to share this row are the toolbar's first group now;
% the file name is the part that has to stay on screen, since two rigs can be
% pointed at different rosters and everything below acts on this one.
self.H.rosterLabel = uilabel(g, 'Text','', 'FontColor',[0.35 0.38 0.42]);
self.H.rosterLabel.Layout.Row = 1;

% ---------- Row 2: projects | subjects ----------------------------------
gMain = uigridlayout(g, [1 2]);
gMain.Layout.Row = 2;
gMain.ColumnWidth = {260, '1x'};
gMain.Padding = [0 0 0 0];
gMain.ColumnSpacing = 10;

% --- left: project list + per-project summary and links
gLeft = uigridlayout(gMain, [5 1]);
gLeft.Layout.Column = 1;
gLeft.RowHeight = {'1x', 22, 28, 'fit', 'fit'};
gLeft.Padding = [0 0 0 0];
gLeft.RowSpacing = 6;

self.H.projectList = uilistbox(gLeft, ...
    'Items', {self.ALL_SUBJECTS}, ...
    'Multiselect','off', ...
    'ValueChangedFcn', @(~,~) self.onProjectChanged_());
self.H.projectList.Layout.Row = 1;

self.H.showArchived = uicheckbox(gLeft, 'Text','Show archived projects', ...
    'Value', localSavedShowArchived(), ...
    'Tooltip','A project selected here stays visible even when this is off.', ...
    'ValueChangedFcn', @(~,~) self.onShowArchivedChanged_());
self.H.showArchived.Layout.Row = 2;

gProjBtns = uigridlayout(gLeft, [1 3]);
gProjBtns.Layout.Row = 3;
gProjBtns.ColumnWidth = {'1x','1x','1x'};
gProjBtns.Padding = [0 0 0 0];
gProjBtns.ColumnSpacing = 4;
self.H.btnNewProject = uibutton(gProjBtns, 'Text','New...', ...
    'ButtonPushedFcn', @(~,~) self.onNewProject_());
self.H.btnEditProject = uibutton(gProjBtns, 'Text','Edit...', ...
    'ButtonPushedFcn', @(~,~) self.onEditProject_());
self.H.btnDeleteProject = uibutton(gProjBtns, 'Text','Delete', ...
    'ButtonPushedFcn', @(~,~) self.onDeleteProject_());

% Read-only summary so the operator can see what a project will apply
% without opening the edit dialog.
self.H.projectSummary = uilabel(gLeft, 'Text','', 'WordWrap','on', ...
    'VerticalAlignment','top', 'FontColor',[0.35 0.38 0.42]);
self.H.projectSummary.Layout.Row = 4;

% The project's links, one uihyperlink per row, rebuilt on every selection by
% updateProjectLinks_. Empty until a project with links is chosen; its rows
% collapse to zero height rather than the panel hiding, because a hidden child
% still claims its cell.
self.H.projectLinks = uigridlayout(gLeft, [1 1]);
self.H.projectLinks.Layout.Row = 5;
self.H.projectLinks.RowHeight = {0};
self.H.projectLinks.ColumnWidth = {'1x'};
self.H.projectLinks.Padding = [0 0 0 0];
self.H.projectLinks.RowSpacing = 2;

% --- right: filter strip, table, action bar
gRight = uigridlayout(gMain, [4 1]);
gRight.Layout.Column = 2;
% Row 2 is the protocol-version banner, collapsed to zero height until there is
% something to say. A hidden child in a 'fit' row still reserves space, so the
% row height itself is what gets toggled -- see showVersionBanner_.
gRight.RowHeight = {28, 0, '1x', 32};
gRight.Padding = [0 0 0 0];
gRight.RowSpacing = 6;
self.H.rightGrid = gRight;

gFilter = uigridlayout(gRight, [1 4]);
gFilter.Layout.Row = 1;
gFilter.ColumnWidth = {'1x', 110, 70, 180};
gFilter.Padding = [0 0 0 0];
gFilter.ColumnSpacing = 6;

% ValueChangingFcn so filtering happens as the operator types. The match is a
% plain case-insensitive contains, never a regex: typing 'M(1' must narrow the
% list, not raise an error.
self.H.filter = uieditfield(gFilter, 'text', ...
    'Placeholder','Filter subjects...', ...
    'ValueChangingFcn', @(~,evt) self.onFilterChanged_(evt.Value), ...
    'ValueChangedFcn', @(~,~) self.onFilterChanged_());

self.H.showRetired = uicheckbox(gFilter, 'Text','Show retired', ...
    'Value', localSavedShowRetired(), ...
    'ValueChangedFcn', @(~,~) self.refresh());

uibutton(gFilter, 'Text','Clear', 'ButtonPushedFcn', @(~,~) self.clearFilter_());

self.H.countLabel = uilabel(gFilter, 'Text','', 'HorizontalAlignment','right', ...
    'FontColor',[0.35 0.38 0.42]);

% ---------- Row 2: protocol-version banner ------------------------------
% Shown only when subjects in this project are behind the protocol file on
% disk. A version mismatch is exactly the thing an operator will not think to
% go looking for, so it announces itself and carries its own fix.
gBanner = uigridlayout(gRight, [1 2]);
gBanner.Layout.Row = 2;
gBanner.ColumnWidth = {'1x', 170};
gBanner.Padding = [8 2 8 2];
gBanner.ColumnSpacing = 8;
gBanner.BackgroundColor = [1.00 0.95 0.85];
self.H.bannerGrid = gBanner;

self.H.bannerLabel = uilabel(gBanner, 'Text','', 'FontColor',[0.60 0.32 0.02], ...
    'VerticalAlignment','center');
self.H.bannerButton = uibutton(gBanner, 'Text','Update All to Latest', ...
    'ButtonPushedFcn', @(~,~) self.onUpdateProtocol_('project'));

self.H.table = uitable(gRight, ...
    'ColumnName', {'', 'Subject', 'Box', 'Protocol', 'Version', 'Species', 'Sex', ...
                   'Weight', 'Last Run', 'Status'}, ...
    'ColumnFormat', {'logical', 'char', 'numeric', 'char', 'char', 'char', 'char', ...
                     'numeric', 'char', 'char'}, ...
    'ColumnEditable', [true false true false false false false false false false], ...
    'ColumnWidth', {30, 140, 50, 170, 110, 90, 70, 60, 130, 70}, ...
    'RowName', {}, ...
    'RowStriping','on', ...
    'SelectionType','row', ...
    'CellEditCallback', @(~,evt) self.onCellEdit_(evt), ...
    'SelectionChangedFcn', @(~,~) self.onSelectionChanged_());
self.H.table.Layout.Row = 3;

% Protocol is read-only in the grid on purpose: uitable's ColumnFormat is
% per-column, so a dropdown there would share one item list across every row
% and could not offer each subject its own remembered protocol.
cm = uicontextmenu(f);
uimenu(cm, 'Text','Set Protocol for This Row...', ...
    'MenuSelectedFcn', @(~,~) self.onSetProtocol_(false));
uimenu(cm, 'Text','Set Protocol for Checked Rows...', ...
    'MenuSelectedFcn', @(~,~) self.onSetProtocol_(true));
self.H.cmnu_open_designer = uimenu(cm, 'Text','Open Protocol in Designer', ...
    'MenuSelectedFcn', @(~,~) self.onOpenInDesigner_());
self.H.cmnu_update_row = uimenu(cm, 'Text','Update to Latest Version', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onUpdateProtocol_('row'));
self.H.cmnu_revert_row = uimenu(cm, 'Text','Revert Protocol Version...', ...
    'MenuSelectedFcn', @(~,~) self.onRevertProtocol_());
uimenu(cm, 'Text','Edit Subject...', 'Separator','on', ...
    'MenuSelectedFcn', @(~,~) self.onEditSubject_());
self.H.table.ContextMenu = cm;

% The empty-state label occupies the table's cell and is shown instead of it.
self.H.emptyState = uilabel(gRight, 'Text','', ...
    'HorizontalAlignment','center', 'VerticalAlignment','center', ...
    'WordWrap','on', 'Visible','off', 'FontColor',[0.35 0.38 0.42]);
self.H.emptyState.Layout.Row = 3;

gActions = uigridlayout(gRight, [1 7]);
gActions.Layout.Row = 4;
gActions.ColumnWidth = {110, 100, 120, 150, 90, '1x', 190};
gActions.Padding = [0 0 0 0];
gActions.ColumnSpacing = 6;

self.H.btnNewSubject = uibutton(gActions, 'Text','New Subject...', ...
    'ButtonPushedFcn', @(~,~) self.onNewSubject_());
self.H.btnEditSubject = uibutton(gActions, 'Text','Edit...', ...
    'ButtonPushedFcn', @(~,~) self.onEditSubject_());
self.H.btnAddToProject = uibutton(gActions, 'Text','Add to Project', ...
    'ButtonPushedFcn', @(~,~) self.onAddToProject_());
self.H.btnRemoveFromProject = uibutton(gActions, 'Text','Remove from Project', ...
    'ButtonPushedFcn', @(~,~) self.onRemoveFromProject_());
self.H.btnRetire = uibutton(gActions, 'Text','Retire', ...
    'ButtonPushedFcn', @(~,~) self.onToggleRetired_());

uilabel(gActions, 'Text','');   % spacer

self.H.btnAddToSession = uibutton(gActions, 'Text','Add Checked to Session', ...
    'FontWeight','bold', ...
    'BackgroundColor',[0.20 0.52 0.85], 'FontColor',[1 1 1], ...
    'ButtonPushedFcn', @(~,~) self.addToSession());

% ---------- Row 3: status line ------------------------------------------
self.H.status = uilabel(g, 'Text','', 'FontColor',[0.35 0.38 0.42]);
self.H.status.Layout.Row = 3;

end

% -----------------------------------------------------------------------
function tf = localSavedShowRetired()
% Remembered across sessions like the selected project.
tf = false;
if ispref('ep_RunExpt_Subjects','ShowRetired')
    tf = logical(getpref('ep_RunExpt_Subjects','ShowRetired'));
end
end

% -----------------------------------------------------------------------
function tf = localSavedShowArchived()
% Remembered across sessions; written by onShowArchivedChanged_.
tf = false;
if ispref('ep_RunExpt_Subjects','ShowArchived')
    tf = logical(getpref('ep_RunExpt_Subjects','ShowArchived'));
end
end
