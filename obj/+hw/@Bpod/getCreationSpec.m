function spec = getCreationSpec()
% spec = hw.Bpod.getCreationSpec()
% Return a hw.InterfaceSpec describing construction options for hw.Bpod.
%
% Consumed by epsych.ProtocolDesigner to build the "Add Interface" form, and by
% getInterfaceEditState to round-trip an existing interface back into that form.
% spec.type must equal char(hw.Bpod.Type) exactly: getInterfaceEditState looks
% the spec up by the interface's Type and errors outright when the lookup fails.
%
% Every option is interface-scoped. Bpod 0.5/0.6 has one main module holding one
% state machine, so there is nothing to scope per hw.Module.
%
% There is deliberately no Baud Rate option. The main module's SerialUSB is
% fixed at 115200, which the class carries as the constant hw.Bpod.BAUD_RATE
% rather than a property — exposing it would invite a rig to be configured into
% a link that cannot handshake, and would also wake up Protocol.toStruct's
% isprop(iface,'BaudRate') branch on every save.
%
% Returns:
%   spec - hw.InterfaceSpec with four options and a factory function.
%
% See also: hw.InterfaceSpec, hw.InterfaceSpecOption, hw.Teensy.getCreationSpec,
%           documentation/hw/hw_Interface_Tutorial.md

options = [ ...
    hw.InterfaceSpecOption( ...
        'name', 'port', ...
        'label', 'Serial Port', ...
        'defaultValue', '', ...
        'required', false, ...
        'inputType', 'text', ...
        'scope', 'interface', ...
        'controlType', 'text', ...
        'description', ['Serial port the Bpod main module enumerates on, e.g. COM3 or ' ...
            '/dev/ttyACM0. Leave empty and enable Auto-detect to probe every available ' ...
            'port with the firmware handshake. The port is machine-specific, so a saved ' ...
            'protocol usually needs it corrected when it moves to another rig.']), ...
    hw.InterfaceSpecOption( ...
        'name', 'autoDetect', ...
        'label', 'Auto-detect port', ...
        'defaultValue', false, ...
        'required', false, ...
        'inputType', 'logical', ...
        'scope', 'interface', ...
        'controlType', 'checkbox', ...
        'description', ['Probe available serial ports at connect and keep the one that ' ...
            'answers the handshake byte. Slower to connect — each candidate pays the ' ...
            'Arduino Due boot delay — but it survives the port number changing between ' ...
            'sessions.']), ...
    hw.InterfaceSpecOption( ...
        'name', 'boxID', ...
        'label', 'Box ID', ...
        'defaultValue', 1, ...
        'required', true, ...
        'inputType', 'numeric', ...
        'scope', 'interface', ...
        'controlType', 'numeric', ...
        'description', ['Subject box this state machine serves. It names the per-box ' ...
            'trigger and result parameters (x_NewTrial_1, x_TrialComplete_1, ...) so ' ...
            'they line up with the rest of the protocol. One Bpod serves exactly one ' ...
            'box: the device has a single state machine, so a second subject would ' ...
            'silently overwrite the first subject''s trial.']), ...
    hw.InterfaceSpecOption( ...
        'name', 'stateMatrixFcn', ...
        'label', 'State Matrix Builder', ...
        'defaultValue', '', ...
        'required', false, ...
        'inputType', 'text', ...
        'scope', 'interface', ...
        'controlType', 'text', ...
        'description', ['Name of a function on the MATLAB path with the signature ' ...
            'sma = f(iface, P), called at each trial to build the state matrix from ' ...
            'the trial''s parameter struct. Give the function NAME, not a file path: ' ...
            'the interface resolves it by name. Leave blank to run in immediate I/O ' ...
            'mode, where MATLAB times the trial and drives the outputs directly.'])];

% The factory reads each field through the tolerant hw.Bpod.optField_ so a
% protocol saved before one of these options existed still constructs.
%
% boxID is coerced through string() before double() so a value that arrives as
% char or string ('2' from a text-backed control, say) parses as the number 2
% rather than its character code. round/max then clamp it onto the positive
% integer the constructor's mustBeInteger/mustBePositive validators demand;
% max() ignores NaN, so an unparseable value falls back to box 1 instead of
% erroring out of the designer.
spec = hw.InterfaceSpec( ...
    char(hw.Bpod.Type), ...
    'Bpod State Machine', ...
    'Connect to a Bpod 0.5/0.6 behavioral state machine over USB serial.', ...
    options, ...
    @(opts) hw.Bpod(char(hw.Bpod.optField_(opts, 'port', '')), ...
        AutoDetect     = logical(hw.Bpod.optField_(opts, 'autoDetect', false)), ...
        BoxID          = max(1, round(double(string(hw.Bpod.optField_(opts, 'boxID', 1))))), ...
        StateMatrixFcn = char(hw.Bpod.optField_(opts, 'stateMatrixFcn', ''))));

end
