function setupPlotAxes_(obj)
% setupPlotAxes_(obj)
% Create and configure graphics objects for the staircase history plot.
%
% Objects are created back-to-front: threshold band, threshold line, the
% staircase trace, step halos, trial markers, then reversal outlines. The
% order is the draw order, so the response color of every trial stays
% visible underneath the overlays that annotate it.
%
% Parameters:
%   obj — psychophysics.Staircase instance

if isempty(obj.plotAxes_) || ~isvalid(obj.plotAxes_)
    return
end

obj.applyAxesStyle_();

xlabel(obj.plotAxes_, 'Trial Index', 'Interpreter', 'none');
ylabel(obj.plotAxes_, obj.yAxisLabel_(), 'Interpreter', 'none');

hold(obj.plotAxes_,'on')

thrColor = hex2rgb(obj.ThresholdColor);

obj.h_thrreg = patch(obj.plotAxes_,nan,nan,thrColor, ...
    EdgeColor='none', ...
    FaceAlpha=0.12);

obj.h_thrline = line(obj.plotAxes_, nan, nan, ...
    'Color', thrColor, ...
    'LineWidth', 2, ...
    'LineStyle', '-', ...
    'Marker', 'none', ...
    'DisplayName', 'Threshold');

obj.h_line = line(obj.plotAxes_, nan, nan, ...
    'Color', hex2rgb(obj.LineColor), ...
    'LineWidth', 1.25, ...
    'LineStyle', '-', ...
    'Marker', 'none', ...
    'DisplayName', 'Staircase');

% Steps are a soft halo behind the trial marker rather than a larger marker
% on top of it, which used to hide the outcome color it duplicates.
obj.StepH = scatter(obj.plotAxes_, nan, nan, obj.StepMarkerSize, ...
    'filled', ...
    'Marker', 'o', ...
    'MarkerEdgeColor', 'none', ...
    'MarkerFaceAlpha', 0.35, ...
    'DisplayName', 'Step', ...
    'Visible', 'off');

% A thin surface-colored ring separates markers that overlap.
obj.h_points = scatter(obj.plotAxes_, nan, nan, obj.MarkerSize, ...
    'filled', ...
    'Marker', 'o', ...
    'MarkerEdgeColor', [1 1 1], ...
    'LineWidth', 0.75, ...
    'DisplayName', 'Stimulus');

obj.CatchH = scatter(obj.plotAxes_, nan, nan, obj.MarkerSize*1.2, ...
    'filled', ...
    'Marker', 'd', ...
    'MarkerEdgeColor', [1 1 1], ...
    'LineWidth', 0.75, ...
    'DisplayName', 'Catch');

% Hollow outlines so a reversal annotates its trial without masking it.
obj.ReversalUpH = scatter(obj.plotAxes_, nan, nan, obj.ReversalMarkerSize, ...
    'Marker', '^', ...
    'MarkerEdgeColor', hex2rgb(obj.ReversalColor), ...
    'MarkerFaceColor', 'none', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Reversal', ...
    'Visible', 'off');

obj.ReversalDownH = scatter(obj.plotAxes_, nan, nan, obj.ReversalMarkerSize, ...
    'Marker', 'v', ...
    'MarkerEdgeColor', hex2rgb(obj.ReversalColor), ...
    'MarkerFaceColor', 'none', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Reversal Down', ...
    'Visible', 'off');

% Legend-only swatches: marker color is the plot's primary encoding, so the
% outcomes present in the data are named in the legend. NaN data draws nothing.
nBits = numel(obj.Bits);
swatches = gobjects(1, nBits);
for idx = 1:nBits
    swatches(idx) = scatter(obj.plotAxes_, nan, nan, obj.MarkerSize, ...
        'filled', ...
        'Marker', 'o', ...
        'MarkerFaceColor', hex2rgb(obj.BitColors(idx)), ...
        'MarkerEdgeColor', [1 1 1], ...
        'LineWidth', 0.75, ...
        'DisplayName', bitDisplayName(obj.Bits(idx)));
end
obj.bitSwatchH_ = swatches;

hold(obj.plotAxes_,'off')

obj.legendKey_ = "";
obj.createPlotContextMenu_();
end

function name = bitDisplayName(bit)
% Split the CamelCase enumeration name into words for the legend.
name = regexprep(char(bit), '([a-z])([A-Z])', '$1 $2');
end
