function T = emptyResults()
% T = util.VideoConverter.emptyResults()
% Return an empty Results table with the correct column names, types, and
% Status categories.
T = table( ...
    zeros(0,1), true(0,1), strings(0,1), strings(0,1), strings(0,1), ...
    zeros(0,1), zeros(0,1), zeros(0,1), zeros(0,1), zeros(0,1), ...
    zeros(0,1), zeros(0,1), zeros(0,1), strings(0,1), strings(0,1), ...
    NaT(0,1), NaT(0,1), ...
    'VariableNames', {'Index','Selected','SourceFile','OutputFile','Status', ...
        'Percent','DurationSec','ElapsedSec','Fps','Speed', ...
        'BytesIn','BytesOut','ExitCode','Message','Args','StartTime','EndTime'});
T.Status = categorical(T.Status, util.VideoConverter.StatusCategories_);
end
